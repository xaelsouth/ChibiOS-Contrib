static uint32_t crcsw_reflect(uint32_t data, uint8_t nbits) {
  uint32_t reflection = 0U;
  for (uint8_t bit = 0; bit < nbits; bit++) {
    if (data & 0x1U) {
      reflection |= (1UL << ((nbits - 1U) - bit));
    }
    data >>= 1;
  }
  return reflection;
}

uint32_t crcsw_update(const crcsw_config_t *cfg, uint32_t crc,
                      const void *blob, size_t bloblen) {
  const uint8_t *p = (const uint8_t *)blob;
  const uint32_t mask = (cfg->width >= 32U) ? 0xFFFFFFFFUL
                                            : ((1UL << cfg->width) - 1UL);

  if (cfg->table != NULL && cfg->refin) {
    /* Reflected (LSB-first) table-driven. */
    for (size_t i = 0; i < bloblen; i++) {
      crc = (crc >> 8) ^ cfg->table[(crc ^ p[i]) & 0xFFU];
    }
  } else if (cfg->table != NULL) {
    /* Normal (MSB-first) table-driven. */
    const uint8_t shift = cfg->width - 8U;
    for (size_t i = 0; i < bloblen; i++) {
      crc = ((crc << 8) & mask) ^ cfg->table[((crc >> shift) ^ p[i]) & 0xFFU];
    }
  } else {
    /* Bitwise fallback (Rocksoft model). */
    for (size_t i = 0; i < bloblen; i++) {
      uint8_t data = p[i];
      if (cfg->refin) {
        data = (uint8_t)crcsw_reflect(data, 8U);
      }
      crc ^= ((uint32_t)data << (cfg->width - 8U));
      for (uint8_t bit = 8; bit > 0; bit--) {
        if (crc & (1UL << (cfg->width - 1U))) {
          crc = ((crc << 1) ^ cfg->poly) & mask;
        } else {
          crc = (crc << 1) & mask;
        }
      }
    }
  }
  return crc & mask;
}

uint32_t crcsw_calc(const crcsw_config_t *cfg, const void *blob, size_t bloblen) {
  const uint32_t mask = (cfg->width >= 32U) ? 0xFFFFFFFFUL
                                            : ((1UL << cfg->width) - 1UL);
  uint32_t crc = crcsw_update(cfg, cfg->init, blob, bloblen);
  if (cfg->refout != cfg->refin) {
    crc = crcsw_reflect(crc, cfg->width);
  }
  return (crc ^ cfg->xorout) & mask;
}


